# ---------- public API ----------


def select_characters(n: int) -> list[CharacterPreset]:
    """随机抽取 n 个角色。"""
    return random.sample(CHARACTER_PRESETS, min(n, len(CHARACTER_PRESETS)))


def get_character_by_id(character_id: str) -> CharacterPreset | None:
    """根据 ID 获取角色预设。"""
    for c in CHARACTER_PRESETS:
        if c.id == character_id:
            return c
    return None


# ---------- backward compatibility ----------

PERSONALITY_TYPES = [c.id for c in CHARACTER_PRESETS]


def assign_personalities(num_players: int) -> list[str]:
    """Assign personality types to AI players (backward compat)."""
    return [c.id for c in select_characters(num_players)]
